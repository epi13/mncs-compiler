//! Generate the MNCS Unicode scalar classifiers from Rust's pinned `char`
//! property tables. Run this tool with the workspace Rust toolchain whenever
//! that toolchain changes, then review the resulting source diff.

use std::env;
use std::fs;
use std::path::PathBuf;
use std::process::Command;

const BEGIN: &str = "// BEGIN GENERATED UNICODE CLASSIFIERS";
const END: &str = "// END GENERATED UNICODE CLASSIFIERS";

fn property_ranges(predicate: fn(char) -> bool) -> Vec<(u32, u32)> {
    let mut ranges = Vec::new();
    let mut start = None;
    let mut previous = 0;
    for scalar in 128..=0x10ffff {
        let included = char::from_u32(scalar).is_some_and(predicate);
        match (start, included) {
            (None, true) => start = Some(scalar),
            (Some(begin), false) => {
                ranges.push((begin, previous));
                start = None;
            }
            _ => {}
        }
        previous = scalar;
    }
    if let Some(begin) = start {
        ranges.push((begin, previous));
    }
    ranges
}

fn emit_property(name: &str, predicate: fn(char) -> bool, output: &mut String) -> usize {
    let ranges = property_ranges(predicate);
    let total = ranges.len();
    output.push_str(&format!(
        "// {name} ranges generated from Rust char properties ({total} intervals above ASCII).\n"
    ));
    output.push_str(&format!(
        "fn unicode_{name}(value: u64) -> (result: bool) {{\n    if value < 128 || value > 1114111 {{ return false; }}\n    return match value / 65536 {{\n"
    ));
    let mut planes = Vec::new();
    for plane in 0..=16 {
        let plane_start = plane * 65536;
        let plane_end = plane_start + 65535;
        let local: Vec<_> = ranges
            .iter()
            .copied()
            .filter(|(low, _)| *low <= plane_end)
            .filter_map(|(low, high)| {
                let clipped_low = low.max(plane_start);
                let clipped_high = high.min(plane_end);
                (clipped_low <= clipped_high).then_some((clipped_low, clipped_high))
            })
            .collect();
        if local.is_empty() {
            continue;
        }
        assert!(
            local.len() <= 1024,
            "plane table exceeds MNCS bounded sequence size"
        );
        planes.push((plane, local));
        output.push_str(&format!(
            "        {plane} => unicode_{name}_plane{plane}(value),\n"
        ));
    }
    output.push_str("        _ => false\n    };\n}\n");
    for (plane, local) in planes {
        output.push_str(&format!(
            "fn unicode_{name}_plane{plane}(value: u64) -> (result: bool) {{\n"
        ));
        output.push_str(&format!(
            "    let ranges: [u64; {}] = [\n        ",
            local.len()
        ));
        for (index, (low, high)) in local.iter().enumerate() {
            if index > 0 {
                if index % 8 == 0 {
                    output.push_str(",\n        ");
                } else {
                    output.push_str(", ");
                }
            }
            // Every scalar is below 2^21, so one u64 stores both inclusive
            // endpoints with room for a future Unicode plane.
            let packed = (u64::from(*low) << 21) | u64::from(*high);
            output.push_str(&packed.to_string());
        }
        output.push_str("\n    ];\n");
        output.push_str(
            "    let initial: UnicodeRangeSearch = UnicodeRangeSearch { low: 0, high: ranges.len, found: false };\n\
iterate step up_to 12 carrying state: UnicodeRangeSearch = initial {\n\
    let active: bool = state.low < state.high && !state.found;\n\
    let midpoint: u64 = select(active, (state.low + state.high) / 2, 0);\n\
    let packed: u64 = ranges[midpoint];\n\
    let low: u64 = packed / 2097152;\n\
    let high: u64 = packed % 2097152;\n\
    let updated: UnicodeRangeSearch = match select(active, 1, 0) {\n\
        0 => state,\n\
        _ => match select(value < low, 1, 0) {\n\
            1 => UnicodeRangeSearch { ..state, high: midpoint },\n\
            _ => match select(value > high, 1, 0) {\n\
                1 => UnicodeRangeSearch { ..state, low: midpoint + 1 },\n\
                _ => UnicodeRangeSearch { ..state, found: true }\n\
            }\n\
        }\n\
    };\n\
    next state = updated;\n\
}\n\
    return state.found;\n",
        );
        output.push_str("}\n");
    }
    total
}

fn generate() -> String {
    let version = Command::new("rustc")
        .arg("--version")
        .output()
        .ok()
        .filter(|result| result.status.success())
        .map(|result| String::from_utf8_lossy(&result.stdout).trim().to_owned())
        .unwrap_or_else(|| "rustc version unavailable".to_owned());
    let mut output =
        format!("{BEGIN}\n// Generated by tools/generate_unicode_classifier.rs using {version}.\n");
    output.push_str("record UnicodeRangeSearch { low: u64, high: u64, found: bool }\n");
    let alphabetic = emit_property("alphabetic", char::is_alphabetic, &mut output);
    let alphanumeric = emit_property("alphanumeric", char::is_alphanumeric, &mut output);
    output.push_str(
        "// Rust char::is_whitespace is represented by the Unicode White_Space property.\n\
fn unicode_whitespace(value: u64) -> (result: bool) {\n\
    return (value >= 9 && value <= 13) || value == 32 || value == 133 || value == 160 ||\n\
        value == 5760 || (value >= 8192 && value <= 8202) || value == 8232 || value == 8233 ||\n\
        value == 8239 || value == 8287 || value == 12288;\n}\n\
fn identifier_start_scalar(value: u64) -> (result: bool) {\n\
    return value == 95 || (value < 128 && ((value >= 65 && value <= 90) || (value >= 97 && value <= 122))) || unicode_alphabetic(value);\n}\n\
fn identifier_continue_scalar(value: u64) -> (result: bool) {\n\
    return value == 95 || (value >= 48 && value <= 57) || (value < 128 && ((value >= 65 && value <= 90) || (value >= 97 && value <= 122))) || unicode_alphanumeric(value);\n}\n\
fn whitespace_scalar(value: u64) -> (result: bool) {\n\
    return (value == 32 || (value >= 9 && value <= 13)) || unicode_whitespace(value);\n}\n\
",
    );
    output.push_str(END);
    eprintln!("generated {alphabetic} alphabetic and {alphanumeric} alphanumeric intervals");
    output
}

fn main() {
    let mut args = env::args().skip(1);
    let mode = args.next().unwrap_or_else(|| "--write".to_owned());
    let path = PathBuf::from(
        args.next()
            .unwrap_or_else(|| "src/compiler/source.mncs".to_owned()),
    );
    if args.next().is_some() || !matches!(mode.as_str(), "--write" | "--check") {
        eprintln!("usage: generate_unicode_classifier.rs [--write|--check] [source.mncs]");
        std::process::exit(2);
    }
    let current = fs::read_to_string(&path).expect("read MNCS source module");
    let begin = current.find(BEGIN).expect("begin marker missing");
    let end = current.find(END).expect("end marker missing");
    assert!(begin < end, "generated markers are out of order");
    let generated = generate();
    let replacement = format!(
        "{}{}{}",
        &current[..begin],
        generated,
        &current[end + END.len()..]
    );
    if mode == "--check" {
        if replacement != current {
            eprintln!("Unicode classifier source differs from generated Rust char tables");
            std::process::exit(1);
        }
    } else {
        fs::write(&path, replacement).expect("write generated MNCS source module");
    }
}
